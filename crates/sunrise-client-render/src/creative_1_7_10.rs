//! Minecraft 1.7.10's creative inventory screen: its ten item tabs, the paged
//! 9x5 grid, the scrollbar and the tab strip of
//! `net/minecraft/client/gui/screen/inventory/menu/CreativeInventoryScreen.java`.
//!
//! The screen is 195x136 and its slots are the era's
//! (`CreativeInventoryScreen$CreativePlayerMenu`): the display grid is nine
//! columns by five rows at `(9 + 18 * column, 18 + 18 * row)` and the player's
//! hotbar row sits at `(9 + 18 * slot, 112)`, both relative to the panel's
//! `(width - 195) / 2, (height - 136) / 2` origin. The grid scrolls when a tab
//! lists more than 45 stacks: `scrollItems` moves the first visible row by
//! `(int)(position * (items / 9 - 5 + 1) + 0.5)`, and the thumb of the track at
//! `(175, 18, 14, 112)` moves by `95` pixels of travel
//! (`renderMenuBackground`, `render`).
//!
//! Two of the era's files draw it: `tab_items.png` (the item tabs' 195x136
//! panel) and `tabs.png` (the 28x32 tab cells at `28 * column`, four rows for
//! the top and bottom strips, selected and unselected, and the scrollbar thumbs
//! at `(232, 0)` and `(244, 0)`).
//!
//! The tabs' contents are the era's own: [`tab_items`] is
//! `CreativeModeTab.addItems` run against the 1.7.10 registry, generated by
//! `tools/javaoracle_1_7_10/CreativeTabs.java` (see its README). The era's
//! remaining two tabs, the search box (id 5) and the player's inventory (id 11),
//! are not drawn here: the survival inventory screen already covers the player's
//! items.

use crate::hud::{HudAtlas, HudBatch};
use crate::hud_1_7_10::Icon;
use crate::items_1_7_10;
use crate::screens_1_7_10::LABEL_COLOR;

/// `InventoryMenuScreen.backgroundWidth`, the 1.7.10 creative screen's.
pub const PANEL_WIDTH: i32 = 195;
/// `InventoryMenuScreen.backgroundHeight` of `CreativeInventoryScreen.init`.
pub const PANEL_HEIGHT: i32 = 136;
/// The 16x16 box one slot occupies.
pub const SLOT_SIZE: i32 = 16;
/// `CreativePlayerMenu`: the slots' pitch.
pub const SLOT_STEP: i32 = 18;
/// `CreativePlayerMenu`: the display grid's first slot.
pub const GRID_X: i32 = 9;
/// `CreativePlayerMenu`: the display grid's first row.
pub const GRID_Y: i32 = 18;
/// `CreativePlayerMenu`: the player's hotbar row.
pub const HOTBAR_Y: i32 = 112;
/// `CreativePlayerMenu`: nine columns.
pub const GRID_COLUMNS: i32 = 9;
/// `CreativePlayerMenu`: five rows.
pub const GRID_ROWS: i32 = 5;
/// The display slots one page holds.
pub const GRID_SLOTS: usize = (GRID_COLUMNS * GRID_ROWS) as usize;
/// The engine slot id of the grid's first slot: the display slots are as
/// ephemeral as 26.3's, so they take 26.3's id range (`Creative::DISPLAY`).
pub const DISPLAY: usize = 900;
/// The tab strip's cells.
pub const TABS_TEXTURE: &str = "gui/container/creative_inventory/tabs";
/// The panel every item tab draws.
pub const ITEMS_PANEL: &str = "gui/container/creative_inventory/tab_items";
/// The scrollbar's track, `renderMenuBackground`'s `(x + 175, y + 18, 14, 112)`.
pub const SCROLL_X: i32 = 175;
pub const SCROLL_Y: i32 = 18;
pub const SCROLL_WIDTH: i32 = 14;
pub const SCROLL_HEIGHT: i32 = 112;
/// The thumb's travel inside the track, `(y + 18 + 112) - (y + 18) - 17`.
pub const SCROLL_TRAVEL: i32 = SCROLL_HEIGHT - 17;
/// The thumb's height, `drawTexture(..., 12, 15)`.
pub const THUMB_HEIGHT: i32 = 15;
/// The tab cells' size, `renderTabIcon`'s 28x32.
pub const TAB_WIDTH: i32 = 28;
pub const TAB_HEIGHT: i32 = 32;
/// How far a tab row reaches outside the panel: 28 above, and
/// `backgroundHeight - 4` + 32 below.
pub const TAB_DEPTH: i32 = 28;
/// `CreativeModeTab.getColumn`: six tabs per row.
pub const TABS_PER_ROW: i32 = 6;

/// One stack a tab lists: the era item id and the metadata (damage) the stack
/// carries.
pub type TabItem17 = (u16, u16);

/// The era's creative tabs, in `CreativeModeTab.ALL`'s order, without the
/// search box and the player's inventory tab.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Tab17 {
    BuildingBlocks,
    Decorations,
    Redstone,
    Transportation,
    Misc,
    Food,
    Tools,
    Combat,
    Brewing,
    Materials,
}

impl Tab17 {
    /// Every tab this screen draws, in `CreativeModeTab.ALL`'s order.
    pub const ALL: [Tab17; 10] = [
        Self::BuildingBlocks,
        Self::Decorations,
        Self::Redstone,
        Self::Transportation,
        Self::Misc,
        Self::Food,
        Self::Tools,
        Self::Combat,
        Self::Brewing,
        Self::Materials,
    ];

    /// `CreativeModeTab.getId`.
    pub fn id(self) -> i32 {
        match self {
            Self::BuildingBlocks => 0,
            Self::Decorations => 1,
            Self::Redstone => 2,
            Self::Transportation => 3,
            Self::Misc => 4,
            Self::Food => 6,
            Self::Tools => 7,
            Self::Combat => 8,
            Self::Brewing => 9,
            Self::Materials => 10,
        }
    }

    /// `CreativeModeTab.getName`, the key behind `itemGroup.<name>`.
    pub fn name(self) -> &'static str {
        match self {
            Self::BuildingBlocks => "buildingBlocks",
            Self::Decorations => "decorations",
            Self::Redstone => "redstone",
            Self::Transportation => "transportation",
            Self::Misc => "misc",
            Self::Food => "food",
            Self::Tools => "tools",
            Self::Combat => "combat",
            Self::Brewing => "brewing",
            Self::Materials => "materials",
        }
    }

    /// `getDisplayName`: the translation key of the tab's title.
    pub fn title_key(self) -> &'static str {
        match self {
            Self::BuildingBlocks => "itemGroup.buildingBlocks",
            Self::Decorations => "itemGroup.decorations",
            Self::Redstone => "itemGroup.redstone",
            Self::Transportation => "itemGroup.transportation",
            Self::Misc => "itemGroup.misc",
            Self::Food => "itemGroup.food",
            Self::Tools => "itemGroup.tools",
            Self::Combat => "itemGroup.combat",
            Self::Brewing => "itemGroup.brewing",
            Self::Materials => "itemGroup.materials",
        }
    }

    /// `getIcon`: the stack the tab's cell draws.
    pub fn icon(self) -> TabItem17 {
        match self {
            Self::BuildingBlocks => (45, 0),
            Self::Decorations => (175, 5),
            Self::Redstone => (331, 0),
            Self::Transportation => (27, 0),
            Self::Misc => (327, 0),
            Self::Food => (260, 0),
            Self::Tools => (258, 0),
            Self::Combat => (283, 0),
            Self::Brewing => (373, 0),
            Self::Materials => (280, 0),
        }
    }

    /// `CreativeModeTab.getColumn`: `id % 6`.
    pub fn column(self) -> i32 {
        self.id() % TABS_PER_ROW
    }

    /// `CreativeModeTab.isTopRow`: `id < 6`.
    pub fn top_row(self) -> bool {
        self.id() < TABS_PER_ROW
    }

    /// `CreativeModeTab.hasScrollbar`: every item tab's list scrolls.
    pub fn has_scrollbar(self) -> bool {
        true
    }

    /// The tab's panel, `tab_items.png`'s 195x136 from its top-left corner.
    pub fn panel(self) -> Icon {
        Icon::at(ITEMS_PANEL, 0, 0, PANEL_WIDTH, PANEL_HEIGHT)
    }

    /// The stacks the tab lists, `CreativeModeTab.addItems`' order.
    pub fn items(self) -> &'static [TabItem17] {
        match self {
            Self::BuildingBlocks => BUILDING_BLOCKS_ITEMS,
            Self::Decorations => DECORATIONS_ITEMS,
            Self::Redstone => REDSTONE_ITEMS,
            Self::Transportation => TRANSPORTATION_ITEMS,
            Self::Misc => MISC_ITEMS,
            Self::Food => FOOD_ITEMS,
            Self::Tools => TOOLS_ITEMS,
            Self::Combat => COMBAT_ITEMS,
            Self::Brewing => BREWING_ITEMS,
            Self::Materials => MATERIALS_ITEMS,
        }
    }

    /// `renderTabIcon`'s cell: where the tab's 28x32 sprite sits relative to the
    /// panel's origin, and the cell's `u`/`v` in `tabs.png`.
    pub fn tab_cell(self, selected: bool) -> TabCell17 {
        let column = self.column();
        let mut x = TAB_WIDTH * column;
        if column == 5 {
            x = PANEL_WIDTH - TAB_WIDTH + 2;
        } else if column > 0 {
            x += column;
        }
        let mut v = 0;
        if selected {
            v += TAB_HEIGHT;
        }
        let y = if self.top_row() {
            -TAB_DEPTH
        } else {
            v += 2 * TAB_HEIGHT;
            PANEL_HEIGHT - 4
        };
        TabCell17 {
            x,
            y,
            u: column * TAB_WIDTH,
            v,
            width: TAB_WIDTH,
            height: TAB_HEIGHT,
        }
    }

    /// The 16x16 icon inside the tab's cell (`renderTabIcon`'s `x += 6`,
    /// `y += 8 + (top ? 1 : -1)`).
    pub fn icon_position(self, selected: bool) -> (i32, i32) {
        let cell = self.tab_cell(selected);
        let dy = if self.top_row() { 1 } else { -1 };
        (cell.x + 6, cell.y + 8 + dy)
    }

    /// `isInRow`: whether a point relative to the panel's origin is on the tab.
    /// The era's rectangle is the strip's `28x32` cell, four pixels off the
    /// drawn one: `-32..0` above the panel and `136..168` below it.
    pub fn contains(self, x: i32, y: i32) -> bool {
        let column = self.column();
        let mut left = TAB_WIDTH * column;
        if column == 5 {
            left = PANEL_WIDTH - TAB_WIDTH + 2;
        } else if column > 0 {
            left += column;
        }
        let top = if self.top_row() {
            -TAB_HEIGHT
        } else {
            PANEL_HEIGHT
        };
        (left..=left + TAB_WIDTH).contains(&x) && (top..=top + TAB_HEIGHT).contains(&y)
    }

    /// The tab under a point relative to the panel's origin.
    pub fn at(x: i32, y: i32) -> Option<Tab17> {
        Self::ALL.into_iter().find(|tab| tab.contains(x, y))
    }
}

/// One tab cell: its place relative to the panel's origin and its sprite in
/// `tabs.png`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TabCell17 {
    pub x: i32,
    pub y: i32,
    pub u: i32,
    pub v: i32,
    pub width: i32,
    pub height: i32,
}

impl TabCell17 {
    /// The cell's sprite in `tabs.png`.
    pub fn sprite(self) -> Icon {
        Icon::at(TABS_TEXTURE, self.u, self.v, self.width, self.height)
    }
}

/// The paged grid of one tab: the era's `scrollItems` over the tab's list.
#[derive(Clone, Copy, Debug)]
pub struct CreativeGrid17<'a> {
    pub tab: Tab17,
    /// The stacks the tab shows, in `addItems` order: [`Tab17::items`] without
    /// the stacks whose item the content root has no registry entry for.
    pub items: &'a [TabItem17],
    /// `scrollPosition`, 0..1.
    pub scroll: f32,
}

impl<'a> CreativeGrid17<'a> {
    pub fn new(tab: Tab17, items: &'a [TabItem17]) -> Self {
        Self {
            tab,
            items,
            scroll: 0.0,
        }
    }

    /// `scrollItems`: how far the list scrolls, `items.size() / 9 - 5 + 1`. One
    /// when the list fits.
    pub fn scroll_rows(&self) -> i32 {
        (self.items.len() / GRID_COLUMNS as usize) as i32 - GRID_ROWS + 1
    }

    /// The first visible row, `(int)(position * rows + 0.5)`.
    pub fn first_row(&self) -> usize {
        let rows = self.scroll_rows().max(1);
        ((self.scroll * rows as f32 + 0.5) as i32).max(0) as usize
    }

    /// The stack shown in display slot `slot` (0..[`GRID_SLOTS`]).
    pub fn shown(&self, slot: usize) -> Option<TabItem17> {
        let index = slot + self.first_row() * GRID_COLUMNS as usize;
        self.items.get(index).copied()
    }

    /// `isMaxTabsReached` as `hasScrollbar()` reads it: the list is longer than
    /// one page of 45.
    pub fn scrollbar(&self) -> bool {
        self.tab.has_scrollbar() && self.items.len() > GRID_SLOTS
    }

    /// The thumb's top, `y + 18 + (int)((112 - 17) * position)`, relative to the
    /// panel's origin.
    pub fn thumb_y(&self) -> i32 {
        SCROLL_Y + (SCROLL_TRAVEL as f32 * self.scroll.clamp(0.0, 1.0)) as i32
    }

    /// `handleMouse`'s wheel: one notch moves `1 / scroll_rows` of the list.
    pub fn wheel(&mut self, delta: f64) {
        if !self.scrollbar() {
            return;
        }
        let rows = self.scroll_rows().max(1);
        let step = if delta > 0.0 { 1.0 } else { -1.0 };
        self.scroll = (self.scroll - step / rows as f32).clamp(0.0, 1.0);
    }

    /// `CreativeInventoryScreen.render`'s drag of the thumb,
    /// `(mouseY - (y + 18) - 7.5) / (112 - 15)`.
    pub fn drag(&mut self, y: f32) {
        if !self.scrollbar() {
            return;
        }
        self.scroll =
            ((y - (SCROLL_Y as f32 + 7.5)) / (SCROLL_HEIGHT as f32 - 15.0)).clamp(0.0, 1.0);
    }

    /// Whether a point relative to the panel's origin is on the scrollbar's
    /// track, `insideScrollbar`.
    pub fn inside_scrollbar(&self, x: f32, y: f32) -> bool {
        self.scrollbar()
            && x >= SCROLL_X as f32
            && x < (SCROLL_X + SCROLL_WIDTH) as f32
            && y >= SCROLL_Y as f32
            && y < (SCROLL_Y + SCROLL_HEIGHT) as f32
    }

    /// Whether a point relative to the panel's origin is on the scrollbar's thumb.
    pub fn inside_thumb(&self, x: f32, y: f32) -> bool {
        self.scrollbar()
            && x >= SCROLL_X as f32
            && x < (SCROLL_X + SCROLL_WIDTH) as f32
            && y >= self.thumb_y() as f32
            && y < (self.thumb_y() + THUMB_HEIGHT) as f32
    }

    /// A display slot's place in the panel, `(9 + 18 * column, 18 + 18 * row)`.
    pub fn slot_position(slot: usize) -> (i32, i32) {
        let column = slot as i32 % GRID_COLUMNS;
        let row = slot as i32 / GRID_COLUMNS;
        (GRID_X + column * SLOT_STEP, GRID_Y + row * SLOT_STEP)
    }

    /// The hotbar row's place in the panel, `(9 + 18 * slot, 112)`.
    pub fn hotbar_position(slot: usize) -> (i32, i32) {
        (GRID_X + slot as i32 * SLOT_STEP, HOTBAR_Y)
    }

    /// The display slot under a point relative to the panel's origin.
    pub fn slot_at(x: f32, y: f32) -> Option<usize> {
        (0..GRID_SLOTS).find(|&slot| {
            let (sx, sy) = Self::slot_position(slot);
            // `AbstractContainerScreen.isHovering`: one pixel around the slot.
            x >= (sx - 1) as f32
                && x < (sx + SLOT_SIZE + 1) as f32
                && y >= (sy - 1) as f32
                && y < (sy + SLOT_SIZE + 1) as f32
        })
    }

    /// The hotbar slot under a point relative to the panel's origin.
    pub fn hotbar_slot_at(x: f32, y: f32) -> Option<usize> {
        (0..9).find(|&slot| {
            let (sx, sy) = Self::hotbar_position(slot);
            x >= (sx - 1) as f32
                && x < (sx + SLOT_SIZE + 1) as f32
                && y >= (sy - 1) as f32
                && y < (sy + SLOT_SIZE + 1) as f32
        })
    }
}

/// Draws the era creative screen at `(ox, oy)`, the panel's origin in GUI
/// pixels: the unselected tabs and their icons, the panel, the scrollbar's
/// thumb, the selected tab and its icon, the tab's title and the display grid.
/// The hotbar row, the hovered slot, the carried stack and the tooltips are the
/// caller's, as is the tab tooltip (`renderTabTooltipIfHovered`).
pub fn paint(
    batch: &mut HudBatch,
    atlas: &HudAtlas,
    grid: &CreativeGrid17<'_>,
    ox: f32,
    oy: f32,
    title: &str,
    tick: u64,
) {
    let draw_sprite = |batch: &mut HudBatch, icon: Icon, x: f32, y: f32| {
        for part in icon.atlas_parts(atlas) {
            batch.rect_uv(
                ox + x + part.dx as f32,
                oy + y + part.dy as f32,
                part.w as f32,
                part.h as f32,
                part.rect,
                u32::MAX,
            );
        }
    };
    // `renderMenuBackground`: every tab but the selected one, then the panel,
    // then the thumb, then the selected tab over the panel's edge. Each tab's
    // 16x16 icon draws over its cell (`renderTabIcon`).
    let draw_cell = |batch: &mut HudBatch, tab: Tab17, selected: bool| {
        let cell = tab.tab_cell(selected);
        for part in cell.sprite().atlas_parts(atlas) {
            batch.rect_uv(
                ox + (cell.x + part.dx) as f32,
                oy + (cell.y + part.dy) as f32,
                part.w as f32,
                part.h as f32,
                part.rect,
                u32::MAX,
            );
        }
        let (id, meta) = tab.icon();
        let (x, y) = tab.icon_position(selected);
        items_1_7_10::paint(batch, atlas, id, meta, ox + x as f32, oy + y as f32, tick);
    };
    for tab in Tab17::ALL {
        if tab == grid.tab {
            continue;
        }
        draw_cell(batch, tab, false);
    }
    draw_sprite(batch, grid.tab.panel(), 0.0, 0.0);
    if grid.scrollbar() {
        // `232 + (hasScrollbar ? 0 : 12), 0, 12, 15`.
        draw_sprite(
            batch,
            Icon::at(TABS_TEXTURE, 232, 0, 12, THUMB_HEIGHT),
            SCROLL_X as f32,
            grid.thumb_y() as f32,
        );
    }
    draw_cell(batch, grid.tab, true);
    // `renderLabels`: the tab's title at (8, 6).
    batch.text(atlas, title, ox + 8.0, oy + 6.0, LABEL_COLOR, false);
    // The display slots' stacks.
    for slot in 0..GRID_SLOTS {
        let Some((id, meta)) = grid.shown(slot) else {
            continue;
        };
        let (x, y) = CreativeGrid17::slot_position(slot);
        items_1_7_10::paint(batch, atlas, id, meta, ox + x as f32, oy + y as f32, tick);
    }
}

