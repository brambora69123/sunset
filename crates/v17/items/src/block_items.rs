/// One `Item.init()` block-loop entry: 64 stack, no damage, the block's key for
/// `tile.` translation. The tab comes from the block's `setCreativeModeTab`.
const fn bitem(
    id: i32,
    name: &'static str,
    block_key: &'static str,
    tab: Option<CreativeTab>,
    kind: BlockItemKind,
) -> ItemDef {
    ItemDef {
        id,
        name,
        key: None,
        max_stack_size: 64,
        max_damage: 0,
        kind: ItemKind::Block(kind),
        tab,
        has_custom_data: kind.has_custom_data(),
        recipe_remainder: None,
        block: Some(id),
        block_key: if block_key.is_empty() {
            None
        } else {
            Some(block_key)
        },
    }
}
