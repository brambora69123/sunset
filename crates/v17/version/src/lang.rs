/// Every key in [`KEY_GROUPS`], in group then file order.
pub fn all_keys() -> impl Iterator<Item = &'static str> {
    KEY_GROUPS.iter().flat_map(|(_, keys)| keys.iter().copied())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_unique() {
        let mut seen = std::collections::HashSet::new();
        for key in all_keys() {
            assert!(seen.insert(key), "duplicate key: {key}");
        }
    }

    #[test]
    fn every_group_carries_keys() {
        for (prefix, keys) in KEY_GROUPS {
            assert!(!keys.is_empty(), "empty group: {prefix}");
            for key in keys.iter() {
                assert!(key.starts_with(prefix), "{key} outside {prefix}");
            }
        }
    }
}
