import java.awt.image.BufferedImage;
import java.io.File;
import javax.imageio.ImageIO;
import net.minecraft.client.world.color.FoliageColors;
import net.minecraft.client.world.color.GrassColors;
import net.minecraft.world.biome.Biome;
import net.minecraft.world.biome.ForestBiome;
import net.minecraft.world.biome.MesaBiome;
import net.minecraft.world.biome.MutatedBiome;
import net.minecraft.world.biome.SwampBiome;

/**
 * The 1.7.10 biome table, entry by entry, as the Rust source the renderer
 * reads (`crates/sunrise-client-render/src/biome_1_7_10.rs`).
 *
 * The two arguments are the era's drawn colormaps, the tables
 * `GrassColors.getColor` and `FoliageColors.get` index by temperature and
 * downfall; `Biome.getGrassColor`/`getFoliageColor` return their own colours
 * for the swamp and the mesa, and the mutated biomes delegate to the biome
 * they mutate. The sky colour is `Biome.getSkyColor(temperature)`, the water
 * fog `Biome.waterFogColor`, and the flags `Biome.rainy`, `Biome.snowy` and
 * `Biome.isHumid()`.
 *
 * Run it after `build.sh`:
 *
 *   sh tools/javaoracle_1_7_10/run.sh BiomeTable \
 *       .local/sunrise-client/1.7.10/assets/minecraft/textures/colormap/grass.png \
 *       .local/sunrise-client/1.7.10/assets/minecraft/textures/colormap/foliage.png
 */
public final class BiomeTable {
    static int[] pixels(BufferedImage image) {
        int[] out = new int[image.getWidth() * image.getHeight()];
        for (int y = 0; y < image.getHeight(); y++) {
            for (int x = 0; x < image.getWidth(); x++) {
                out[y * image.getWidth() + x] = image.getRGB(x, y);
            }
        }
        return out;
    }

    /** `Biome.name` as a registry path: "Extreme Hills+" becomes `extreme_hills_plus`. */
    static String registry(String name) {
        StringBuilder out = new StringBuilder("minecraft:");
        boolean lower = false;
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isLetterOrDigit(c)) {
                if (Character.isUpperCase(c) && lower) {
                    out.append('_');
                }
                out.append(Character.toLowerCase(c));
                lower = Character.isLowerCase(c);
            } else if (c == '+') {
                out.append("_plus");
                lower = true;
            } else if ((c == ' ' || c == '_') && out.charAt(out.length() - 1) != '_') {
                out.append('_');
                lower = false;
            }
        }
        return out.toString();
    }

    /** The biome a mutated one mutates (`MutatedBiome.original`), through every level. */
    static Biome original(Biome biome) {
        while (biome instanceof MutatedBiome) {
            biome = ((MutatedBiome) biome).original;
        }
        return biome;
    }

    static String modifier(Biome biome) {
        Biome base = original(biome);
        if (base instanceof SwampBiome) {
            return "GrassModifier::Swamp";
        }
        if (base instanceof MesaBiome) {
            return "GrassModifier::Fixed";
        }
        if (base instanceof ForestBiome && base.id == Biome.ROOFED_FOREST.id) {
            return "GrassModifier::DarkForest";
        }
        return "GrassModifier::None";
    }

    static float clamp(float value) {
        return Math.max(0.0F, Math.min(1.0F, value));
    }

    public static void main(String[] args) throws Exception {
        GrassColors.set(pixels(ImageIO.read(new File(args[0]))));
        FoliageColors.set(pixels(ImageIO.read(new File(args[1]))));
        System.out.println("//! The 1.7.10 biome table: every entry of `Biome`'s `BY_ID`, as the era's");
        System.out.println("//! own classes build it (`tools/javaoracle_1_7_10/BiomeTable.java`).");
        System.out.println("//!");
        System.out.println("//! Generated by `tools/javaoracle_1_7_10/run.sh BiomeTable <grass.png> <foliage.png>`");
        System.out.println("//! (after `build.sh`): do not edit by hand. Regenerate when the era's biome");
        System.out.println("//! classes change.");
        System.out.println();
        System.out.println("use crate::biome::GrassModifier;");
        System.out.println();
        System.out.println("/// One `Biome` of the era's table, by its own id.");
        System.out.println("pub(crate) struct EraBiome {");
        System.out.println("    /// The era's id: the byte a chunk's `Biomes` array holds.");
        System.out.println("    pub id: u8,");
        System.out.println("    /// `Biome.name`, in registry form.");
        System.out.println("    pub name: &'static str,");
        System.out.println("    /// `Biome.temperature`, the era's own (negative in the cold taigas).");
        System.out.println("    pub temperature: f32,");
        System.out.println("    /// `Biome.downfall`.");
        System.out.println("    pub downfall: f32,");
        System.out.println("    /// `Biome$Height.baseHeight` and `heightModifier`.");
        System.out.println("    pub height: [f32; 2],");
        System.out.println("    /// `Biome.getSkyColor(temperature)`, 0xRRGGBB.");
        System.out.println("    pub sky: u32,");
        System.out.println("    /// `GrassColors.getColor` at the base climate; the swamp's own");
        System.out.println("    /// `0x6A7039`; the mesa's fixed `getGrassColor`.");
        System.out.println("    pub grass: u32,");
        System.out.println("    /// `FoliageColors.get` at the base climate; the swamp's and the mesa's");
        System.out.println("    /// fixed `getFoliageColor`.");
        System.out.println("    pub foliage: u32,");
        System.out.println("    /// How the grass colour moves with position (`Biome.getGrassColor`'s");
        System.out.println("    /// overrides; the swamp's and the roofed forest's).");
        System.out.println("    pub modifier: GrassModifier,");
        System.out.println("    /// `Biome.waterFogColor`: `LiquidBlock`'s underwater fog colour.");
        System.out.println("    pub water_fog: u32,");
        System.out.println("    /// `Biome.isCold()`: the biome snows.");
        System.out.println("    pub snowy: bool,");
        System.out.println("    /// `Biome.rainy` (`isRainy()` is false in a cold biome: it snows).");
        System.out.println("    pub rainy: bool,");
        System.out.println("    /// `Biome.isHumid()`: downfall above 0.85.");
        System.out.println("    pub humid: bool,");
        System.out.println("}");
        System.out.println();
        System.out.println("/// The era's biomes in id order. An id the layers never produce is absent:");
        System.out.println("/// it reads as plains.");
        System.out.println("pub(crate) static ERA_BIOMES: &[EraBiome] = &[");
        Biome[] all = Biome.getAll();
        for (int id = 0; id < all.length; id++) {
            Biome biome = all[id];
            if (biome == null) {
                continue;
            }
            if (biome.id != id) {
                System.out.printf("    // %d is the same `Biome` object as %d.%n", id, biome.id);
            }
            String modifier = modifier(biome);
            double temperature = clamp(biome.temperature);
            double downfall = clamp(biome.downfall);
            int grass = GrassColors.getColor(temperature, downfall) & 0xFFFFFF;
            int foliage = FoliageColors.get(temperature, downfall) & 0xFFFFFF;
            if (modifier.equals("GrassModifier::Swamp")) {
                // `SwampBiome.getGrassColor`/`getFoliageColor` ignore the colormaps.
                grass = 0x6A7039;
                foliage = 0x6A7039;
            } else if (modifier.equals("GrassModifier::Fixed")) {
                grass = original(biome).getGrassColor(0, 64, 0) & 0xFFFFFF;
                foliage = original(biome).getFoliageColor(0, 64, 0) & 0xFFFFFF;
            }
            int sky = biome.getSkyColor(biome.temperature) & 0xFFFFFF;
            System.out.printf(
                "    EraBiome { id: %d, name: \"%s\", temperature: %s, downfall: %s, "
                    + "height: [%s, %s], sky: 0x%06X, grass: 0x%06X, foliage: 0x%06X, "
                    + "modifier: %s, water_fog: 0x%06X, snowy: %b, rainy: %b, humid: %b },%n",
                id, registry(biome.name), Float.toString(biome.temperature),
                Float.toString(biome.downfall), Float.toString(biome.baseHeight),
                Float.toString(biome.heightVariation), sky, grass, foliage, modifier,
                biome.waterFogColor & 0xFFFFFF, biome.isCold(), biome.rainy, biome.isHumid());
        }
        System.out.println("];");
    }
}
